"""Workbook generation with XlsxWriter.

Spec (all data comes from backend services, never from model-written numbers):
{
  "title": "Sales October 2026",
  "dashboard": {"kpis": [{"label": "Net Sales", "value": 123.4, "format": "currency"}], "notes": [...],
                "chart": {"sheet": "By Customer", "type": "column", "category": "customer", "values": ["net_sales"]}},
  "sheets": [{"name": "By Customer", "columns": [{"key": "customer", "label": "Customer", "type": "text"}, ...],
              "rows": [[...], ...], "totals": ["net_sales"], "conditional": [{"column": "net_sales", "rule": "data_bar"}],
              "chart": {"type": "bar", "category": "customer", "values": ["net_sales"], "title": "..."}}],
  "source": {"method": "...", "filters": {...}, "doctypes": [...], "generated_by": "..."}
}
"""

from __future__ import annotations

import datetime as dt
import io

import xlsxwriter
from xlsxwriter.utility import xl_col_to_name, xl_rowcol_to_cell

FORMATS = {
	"currency": "#,##,##0.00",
	"number": "#,##0.##",
	"integer": "#,##0",
	"percent": "0.0%",
	"date": "dd-mm-yyyy",
	"text": "@",
}
CHART_TYPES = {"column", "bar", "line", "pie"}
MAX_COL_WIDTH = 50
FORMULA_TRIGGERS = ("=", "+", "-", "@", "\t", "\r")


def _sheet_name(name: str, used: set) -> str:
	clean = "".join(ch for ch in str(name) if ch not in '[]:*?/\\')[:31] or "Sheet"
	base, n = clean, 2
	while clean.lower() in used:
		clean = f"{base[:28]}~{n}"
		n += 1
	used.add(clean.lower())
	return clean


class Builder:
	def __init__(self):
		self.buf = io.BytesIO()
		self.wb = xlsxwriter.Workbook(self.buf, {"in_memory": True, "strings_to_formulas": False,
												 "strings_to_urls": False, "default_date_format": FORMATS["date"]})
		self.f = {
			"title": self.wb.add_format({"bold": True, "font_size": 16, "font_color": "#3730a3"}),
			"sub": self.wb.add_format({"italic": True, "font_color": "#6b7280"}),
			"header": self.wb.add_format({"bold": True, "font_color": "#ffffff", "bg_color": "#4f46e5",
										  "border": 1, "text_wrap": True, "valign": "vcenter"}),
			"kpi_label": self.wb.add_format({"bold": True, "font_color": "#6b7280", "font_size": 10}),
			"kpi_value": self.wb.add_format({"bold": True, "font_size": 18, "num_format": FORMATS["currency"]}),
			"kpi_value_num": self.wb.add_format({"bold": True, "font_size": 18, "num_format": FORMATS["number"]}),
			"neg": self.wb.add_format({"font_color": "#b91c1c"}),
		}
		self.num_formats = {k: self.wb.add_format({"num_format": v}) for k, v in FORMATS.items()}
		self.used = set()
		self.sheet_cells = {}

	def write_cell(self, ws, r, c, value, ctype):
		if value is None or value == "":
			ws.write_blank(r, c, None)
		elif isinstance(value, bool):
			ws.write_boolean(r, c, value)
		elif isinstance(value, (int, float)):
			ws.write_number(r, c, value, self.num_formats.get(ctype if ctype != "text" else "number"))
		elif isinstance(value, (dt.date, dt.datetime)):
			ws.write_datetime(r, c, value if isinstance(value, dt.datetime) else dt.datetime.combine(value, dt.time()),
							  self.num_formats["date"])
		else:
			# Always text: values starting with = + - @ can never become formulas (formula injection).
			ws.write_string(r, c, str(value))

	def add_table_sheet(self, sheet: dict, title: str | None = None):
		name = _sheet_name(sheet.get("name") or "Data", self.used)
		ws = self.wb.add_worksheet(name)
		cols = sheet["columns"]
		rows = sheet.get("rows") or []
		ws.set_header(f"&L&B{(title or name)[:60]}&R&D")
		ws.set_footer("&LGenerated by Chikku AI&RPage &P of &N")
		ws.set_landscape()
		ws.fit_to_pages(1, 0)
		start = 0
		if title:
			ws.write_string(0, 0, title, self.f["title"])
			start = 2
		widths = [len(str(c.get("label") or c["key"])) + 2 for c in cols]
		for r_i, row in enumerate(rows):
			for c_i, col in enumerate(cols):
				v = row[c_i] if c_i < len(row) else None
				self.write_cell(ws, start + 1 + r_i, c_i, v, col.get("type", "text"))
				widths[c_i] = max(widths[c_i], min(len(str(v)) + 2 if v is not None else 0, MAX_COL_WIDTH))
		totals = set(sheet.get("totals") or [])
		last_row = start + len(rows)
		if cols:
			table_cols = []
			for c_i, col in enumerate(cols):
				tc = {"header": str(col.get("label") or col["key"])[:255], "header_format": self.f["header"]}
				if col["key"] in totals:
					tc["total_function"] = "sum"
					tc["format"] = self.num_formats.get(col.get("type", "number"))
				table_cols.append(tc)
			if cols and cols[0]["key"] not in totals and totals:
				table_cols[0]["total_string"] = "Total"
			ws.add_table(start, 0, last_row + (1 if totals else 0), len(cols) - 1, {
				"columns": table_cols, "style": "Table Style Medium 2", "autofilter": True,
				"total_row": bool(totals), "name": f"T_{len(self.used)}_{abs(hash(name)) % 10000}",
			})
		for c_i, w in enumerate(widths):
			ws.set_column(c_i, c_i, min(max(w, 8), MAX_COL_WIDTH))
		ws.freeze_panes(start + 1, 1 if len(cols) > 3 else 0)
		for cond in sheet.get("conditional") or []:
			if cond.get("column") not in [c["key"] for c in cols] or not rows:
				continue
			ci = [c["key"] for c in cols].index(cond["column"])
			rng = (start + 1, ci, last_row, ci)
			if cond.get("rule") == "data_bar":
				ws.conditional_format(*rng, {"type": "data_bar", "bar_color": "#818cf8", "bar_solid": True})
			elif cond.get("rule") == "negative":
				ws.conditional_format(*rng, {"type": "cell", "criteria": "<", "value": 0, "format": self.f["neg"]})
			elif cond.get("rule") == "top10":
				ws.conditional_format(*rng, {"type": "top", "value": 10,
											 "format": self.wb.add_format({"bg_color": "#dcfce7"})})
		self.sheet_cells[sheet.get("name")] = {"ws": ws, "name": name, "cols": cols, "start": start, "rows": len(rows)}
		if sheet.get("chart") and rows:
			self.add_chart(sheet["chart"], sheet.get("name"), ws, f"{xl_col_to_name(len(cols) + 1)}{start + 2}")
		return ws

	def add_chart(self, spec: dict, sheet_key: str, target_ws, anchor: str):
		info = self.sheet_cells.get(sheet_key)
		if not info or not info["rows"]:
			return
		ctype = spec.get("type", "column") if spec.get("type") in CHART_TYPES else "column"
		chart = self.wb.add_chart({"type": ctype})
		keys = [c["key"] for c in info["cols"]]
		if spec.get("category") not in keys:
			return
		cat = keys.index(spec["category"])
		first, last = info["start"] + 1, info["start"] + min(info["rows"], 50)
		for vkey in (spec.get("values") or [])[:4]:
			if vkey not in keys:
				continue
			vi = keys.index(vkey)
			chart.add_series({
				"name": str(info["cols"][vi].get("label") or vkey),
				"categories": [info["name"], first, cat, last, cat],
				"values": [info["name"], first, vi, last, vi],
				**({"data_labels": {"percentage": True}} if ctype == "pie" else {}),
			})
		chart.set_title({"name": spec.get("title") or ""})
		chart.set_legend({"position": "bottom" if ctype != "pie" else "right"})
		chart.set_size({"width": 620, "height": 340})
		target_ws.insert_chart(anchor, chart)

	def add_dashboard(self, title: str, dash: dict, source: dict | None):
		ws = self.wb.add_worksheet(_sheet_name("Dashboard", self.used))
		ws.hide_gridlines(2)
		ws.set_column(0, 0, 2)
		ws.set_column(1, 8, 20)
		ws.write_string(0, 1, title, self.f["title"])
		if source and source.get("period"):
			ws.write_string(1, 1, f"Period: {source['period']}", self.f["sub"])
		for i, k in enumerate((dash.get("kpis") or [])[:8]):
			r, c = 3 + (i // 4) * 3, 1 + (i % 4) * 2
			ws.write_string(r, c, str(k.get("label", ""))[:60], self.f["kpi_label"])
			val = k.get("value")
			if isinstance(val, (int, float)):
				ws.write_number(r + 1, c, val, self.f["kpi_value"] if k.get("format") == "currency" else self.f["kpi_value_num"])
			else:
				ws.write_string(r + 1, c, str(val if val is not None else "—"))
		row = 10
		for note in (dash.get("notes") or [])[:10]:
			ws.write_string(row, 1, str(note)[:250])
			row += 1
		return ws

	def add_source_sheet(self, source: dict):
		ws = self.wb.add_worksheet(_sheet_name("Source", self.used))
		ws.set_column(0, 0, 24)
		ws.set_column(1, 1, 90)
		ws.write_string(0, 0, "How these figures were produced", self.f["title"])
		r = 2
		for k, v in source.items():
			ws.write_string(r, 0, str(k).replace("_", " ").title())
			ws.write_string(r, 1, v if isinstance(v, str) else str(v))
			r += 1

	def close(self) -> bytes:
		self.wb.close()
		return self.buf.getvalue()


def build(spec: dict) -> bytes:
	b = Builder()
	title = str(spec.get("title") or "Chikku AI Report")[:120]
	dashboard_ws = b.add_dashboard(title, spec["dashboard"], spec.get("source")) if spec.get("dashboard") else None
	for sheet in spec.get("sheets") or []:
		b.add_table_sheet(sheet, title=sheet.get("title"))
	if dashboard_ws is not None and (spec.get("dashboard") or {}).get("chart"):
		ch = spec["dashboard"]["chart"]
		b.add_chart(ch, ch.get("sheet"), dashboard_ws, "B13")
	if spec.get("source"):
		b.add_source_sheet(spec["source"])
	if not spec.get("sheets") and dashboard_ws is None:
		b.wb.add_worksheet("Empty").write_string(0, 0, "No data")
	return b.close()


def cell_ref(row: int, col: int) -> str:
	return xl_rowcol_to_cell(row, col)
